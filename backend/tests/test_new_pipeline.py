class TestIrisExtraction:
    def test_normal_row(self):
        row = SimpleNamespace(plateNumber="sk041h", chargedAmount=4.5,
                              totalCardAmount=4.5, totalCashAmount=0)
        assert _extract_plate(row) == "SK041H"

    def test_typed_input_noise_removed(self):
        row = SimpleNamespace(plateNumber=" ab 123-c ", chargedAmount=2.0,
                              totalCardAmount=0, totalCashAmount=0)
        assert _extract_plate(row) == "AB123C"

    def test_sk_prefix_never_stripped(self):
        """SK041H bug regression: SK looks like Saskatchewan but is the plate."""
        row = SimpleNamespace(plateNumber="SK041H", chargedAmount=1.0,
                              totalCardAmount=0, totalCashAmount=0)
        assert _extract_plate(row) == "SK041H"

    def test_no_plate_discarded(self):
        row = SimpleNamespace(plateNumber=None, chargedAmount=4.5,
                              totalCardAmount=0, totalCashAmount=0)
        assert _extract_plate(row) == ""

    def test_zero_value_transaction_kept(self):
        """$0 transactions (coupons / free periods) ARE payments -- the
        report includes them; filtering them removed 446 April plates."""
        row = SimpleNamespace(plateNumber="AB123C", chargedAmount=0,
                              totalCardAmount=0, totalCashAmount=0)
        assert _extract_plate(row) == "AB123C"

    def test_cash_only_transaction_kept(self):
        row = SimpleNamespace(plateNumber="AB123C", chargedAmount=0,
                              totalCardAmount=None, totalCashAmount=3.0)
        assert _extract_plate(row) == "AB123C"

    def test_missing_amount_fields_kept(self):
        row = SimpleNamespace(plateNumber="AB123C", chargedAmount=None,
                              totalCardAmount=None, totalCashAmount=None)
        assert _extract_plate(row) == "AB123C"


class TestIrisUtcWindows:
    """The campus-local month must map to exact UTC day-windows.
    April 2026 in America/Vancouver is PDT (UTC-7)."""

    def test_april_2026(self):
        from app.integrations.t2_iris import _month_utc_windows
        windows = _month_utc_windows(2026, 4)
        # Apr 1 00:00 PDT = Apr 1 07:00 UTC; Apr 30 23:59:59 PDT = May 1 06:59:59 UTC
        assert windows[0][0] == datetime(2026, 4, 1, 7, 0, 0)
        assert windows[-1][1] == datetime(2026, 5, 1, 6, 59, 59)
        # every window stays within one UTC calendar day
        for start, end in windows:
            assert start.date() == end.date()
            assert start <= end
        # contiguous coverage: 30 full days needs 31 windows (two partials)
        assert len(windows) == 31


