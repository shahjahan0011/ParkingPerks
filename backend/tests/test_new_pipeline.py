def _reads_xlsx_bytes(tmp_path) -> bytes:
    f = tmp_path / "April_export.xlsx"
    rows = []
    # SK041H: 3 qualifying days (>= 1h span each)
    for day in (10, 11, 12):
        rows.append(("SK041H", datetime(2026, 4, day, 9, 0, 0)))
        rows.append(("SK041H", datetime(2026, 4, day, 11, 0, 0)))
    # AB123C: visits but spans < 1h -> not qualifying
    for day in (10, 11, 12):
        rows.append(("AB123C", datetime(2026, 4, day, 9, 0, 0)))
        rows.append(("AB123C", datetime(2026, 4, day, 9, 20, 0)))
    _write_new_format(f, rows)
    return f.read_bytes()


class TestEndToEnd:
    def test_full_flow(self, client, tmp_path):
        # No reads uploaded yet -> analyze fails with a clear message
        r = client.post("/api/analyze", json={"year": 2026, "month": 4, "min_visits": 3, "actor": "test"})
        assert r.status_code == 422
        assert "No plate reads available" in r.json()["detail"]

        # Upload the reads export
        r = client.post(
            "/api/upload/reads",
            files={"file": ("April_export.xlsx", _reads_xlsx_bytes(tmp_path),
                            "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet")},
        )
        assert r.status_code == 200, r.text
        assert r.json()["months_covered"] == ["2026-04"]

        # Analyze: SK041H qualifies via payment track; permit holders via permit track
        r = client.post("/api/analyze", json={"year": 2026, "month": 4, "min_visits": 3, "actor": "test"})
        assert r.status_code == 200, r.text
        body = r.json()
        plates = {q["plate"]: q["track"] for q in body["qualifiers"]}
        assert plates["SK041H"] == "payment"
        assert plates["XY987Z"] == "permit"
        assert plates["NOMAIL1"] == "permit"
        assert "AB123C" not in plates  # span too short
        assert body["summary"]["final"] == 3

        # Wrong month -> friendly error
        r = client.post("/api/analyze", json={"year": 2026, "month": 5, "min_visits": 3, "actor": "test"})
        assert r.status_code == 422
        assert "2026-05" in r.json()["detail"]

        # Draw without a name -> rejected
        r = client.post("/api/draw", json={"year": 2026, "month": 4, "num_winners": 1,
                                           "min_visits": 3, "actor": "  "})
        assert r.status_code == 400

        # Draw
        r = client.post("/api/draw", json={"year": 2026, "month": 4, "num_winners": 1,
                                           "min_visits": 3, "actor": "test"})
        assert r.status_code == 200, r.text
        d = r.json()
        assert d["pool_size"] == 3
        assert len(d["winners"]) == 1
        assert d["is_redraw"] is False

        # Redraw without manager code -> blocked
        r = client.post("/api/draw", json={"year": 2026, "month": 4, "num_winners": 1,
                                           "min_visits": 3, "actor": "test"})
        assert r.status_code == 403

        # Redraw with manager code -> allowed
        from app.config import settings
        r = client.post("/api/draw", json={"year": 2026, "month": 4, "num_winners": 1,
                                           "min_visits": 3, "actor": "test",
                                           "manager_code": settings.manager_code})
        assert r.status_code == 200
        assert r.json()["is_redraw"] is True

        # History shows exactly one record for the month
        r = client.get("/api/history")
        assert r.status_code == 200
        months = [row["month"] for row in r.json()]
        assert months.count("2026-04") == 1
