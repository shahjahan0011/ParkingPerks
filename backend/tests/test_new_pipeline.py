EXCEL_EPOCH = datetime(1899, 12, 30)


def _serial(dt: datetime) -> float:
    return (dt - EXCEL_EPOCH).total_seconds() / 86400


def _write_new_format(path, rows):
    """Genetec Security Desk export: 6 junk rows, header on row 7, serial timestamps."""
    wb = Workbook()
    ws = wb.active
    for _ in range(6):
        ws.append(["Report generated by Security Desk", None])
    ws.append(["Plate read", "Read timestamp"])
    for plate, dt in rows:
        ws.append([plate, _serial(dt)])
    wb.save(path)


def _write_old_format(path, rows):
    """Cloudrunner export: 1 junk row, header on row 2, string timestamps."""
    wb = Workbook()
    ws = wb.active
    ws.append(["Cloudrunner report", None])
    ws.append(["Plate number", "Local time (PDT)"])
    for plate, dt in rows:
        ws.append([plate, dt.strftime("%m/%d/%Y, %I:%M:%S %p")])
    wb.save(path)


