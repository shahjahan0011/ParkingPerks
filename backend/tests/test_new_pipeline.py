class TestReadsParser:
    def test_new_format_parses(self, tmp_path):
        f = tmp_path / "reads.xlsx"
        _write_new_format(f, [
            ("SK041H", datetime(2026, 4, 15, 9, 0, 0)),
            ("AB123C", datetime(2026, 4, 15, 10, 30, 0)),
        ])
        df = _parse_reads_file(f)
        assert sorted(df["plate"]) == ["AB123C", "SK041H"]

    def test_old_format_parses(self, tmp_path):
        f = tmp_path / "reads.xlsx"
        _write_old_format(f, [("SK041H", datetime(2026, 4, 15, 9, 0, 0))])
        df = _parse_reads_file(f)
        assert list(df["plate"]) == ["SK041H"]

    def test_utc_bug_regression_late_evening_read_keeps_local_date(self, tmp_path):
        """A read at 11:56 PM must stay on the same calendar date (the old
        toISOString bug shifted it to the next day)."""
        f = tmp_path / "reads.xlsx"
        late = datetime(2026, 4, 30, 23, 56, 9)
        _write_new_format(f, [("SK041H", late)])
        df = _parse_reads_file(f)
        assert df["ts"].iloc[0].date() == late.date()
        assert df["ts"].iloc[0].hour == 23

    def test_month_filter_rejects_wrong_month(self, tmp_path):
        f = tmp_path / "reads.xlsx"
        _write_new_format(f, [("SK041H", datetime(2026, 4, 15, 9, 0, 0))])
        df = _parse_reads_file(f)
        with pytest.raises(ReadsFileError, match="2026-05"):
            _reads_for_month(df, 2026, 5, source="reads.xlsx")

    def test_month_filter_keeps_right_month_only(self, tmp_path):
        f = tmp_path / "reads.xlsx"
        _write_new_format(f, [
            ("SK041H", datetime(2026, 4, 15, 9, 0, 0)),
            ("ZZ999Z", datetime(2026, 5, 1, 0, 5, 0)),  # spillover row
        ])
        df = _parse_reads_file(f)
        reads = _reads_for_month(df, 2026, 4, source="reads.xlsx")
        assert [r.plate for r in reads] == ["SK041H"]

    def test_not_a_reads_file(self, tmp_path):
        f = tmp_path / "junk.xlsx"
        wb = Workbook()
        ws = wb.active
        ws.append(["Totally", "Unrelated"])
        ws.append(["a", "b"])
        wb.save(f)
        with pytest.raises(ReadsFileError, match="does not look like"):
            _parse_reads_file(f)

    def test_inspect_reports_coverage(self, tmp_path):
        f = tmp_path / "reads.xlsx"
        _write_new_format(f, [
            ("SK041H", datetime(2026, 4, 1, 9, 0, 0)),
            ("SK041H", datetime(2026, 4, 30, 9, 0, 0)),
        ])
        info = inspect_reads_file(f)
        assert info.total_rows == 2
        assert info.date_min == "2026-04-01"
        assert info.date_max == "2026-04-30"
        assert info.months_covered == ["2026-04"]


